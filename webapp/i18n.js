  function normalize(code) {
    return String(code || '').toLowerCase().split(/[-_]/)[0] === 'ru' ? 'ru' : 'en';
  }

  function translateText(value, language) {
    if (language !== 'en') return value;
    const leading = value.match(/^\s*/)?.[0] || '';
    const trailing = value.match(/\s*$/)?.[0] || '';
    const text = value.trim();
    if (!text) return value;
    if (en[text]) return `${leading}${en[text]}${trailing}`;
    const patterns = [
      [/^Серия (\d+)$/, 'Streak $1'],
      [/^(\d+) задач$/, '$1 puzzles'],
      [/^(\d+) партий$/, '$1 games'],
      [/^Приглашено: (\d+)$/, 'Invited: $1'],
      [/^Сыграно: (\d+)$/, 'Played: $1'],
      [/^Верно: (.+)$/, 'Correct: $1'],
    ];
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(text)) return `${leading}${text.replace(pattern, replacement)}${trailing}`;
    }
    return value;
  }

  function apply(root, language) {
    const lang = normalize(language);
    document.documentElement.lang = lang;
    if (!root || lang !== 'en') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => { node.nodeValue = translateText(node.nodeValue, lang); });
    root.querySelectorAll('[placeholder],[title],[aria-label],optgroup[label]').forEach(el => {
      ['placeholder', 'title', 'aria-label', 'label'].forEach(attr => {
        if (el.hasAttribute(attr)) el.setAttribute(attr, translateText(el.getAttribute(attr), lang));
      });
    });
  }

  window.ChessMeetI18n = { normalize, apply, text: translateText };
